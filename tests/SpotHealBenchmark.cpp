double noise(int x,int y,unsigned seed)
{
    std::uint32_t v=std::uint32_t(x)*0x9e3779b9U^std::uint32_t(y)*0x85ebca6bU^seed;
    v^=v>>16;v*=0x7feb352dU;v^=v>>15;v*=0x846ca68bU;v^=v>>16;
    return double(v)/double(std::numeric_limits<std::uint32_t>::max())*2-1;
}
double smoothNoise(double x,double y,unsigned seed)
{
    const int ix=int(std::floor(x)),iy=int(std::floor(y));
    double tx=x-ix,ty=y-iy;tx=tx*tx*(3-2*tx);ty=ty*ty*(3-2*ty);
    return std::lerp(std::lerp(noise(ix,iy,seed),noise(ix+1,iy,seed),tx),
        std::lerp(noise(ix,iy+1,seed),noise(ix+1,iy+1,seed),tx),ty);
}
PremultipliedColor color(double red,double green,double blue,double alpha=1)
{
    return {float(std::clamp(red,0.,1.)*alpha),float(std::clamp(green,0.,1.)*alpha),
        float(std::clamp(blue,0.,1.)*alpha),float(alpha)};
}
