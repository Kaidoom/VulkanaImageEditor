std::string fingerprint(const void* data,std::size_t bytes)
{
    return QCryptographicHash::hash(QByteArrayView(static_cast<const char*>(data),qsizetype(bytes)),QCryptographicHash::Sha256).toHex().toStdString();
}
double cpuMilliseconds()
{
    rusage usage{};getrusage(RUSAGE_SELF,&usage);
    return (double(usage.ru_utime.tv_sec)+double(usage.ru_stime.tv_sec))*1000.
        +(double(usage.ru_utime.tv_usec)+double(usage.ru_stime.tv_usec))/1000.;
}
int performance(PerformanceCase test)
{
    QImage photograph;
    if(!test.photo.isEmpty()){
        photograph=QImage(test.photo).convertToFormat(QImage::Format_RGBA8888);
        if(photograph.isNull()){std::cerr<<"Unable to load photographic fixture\n";return 2;}
        test.width=photograph.width();test.height=photograph.height();
    }
    const auto w=test.width,h=test.height;const bool retouch=test.retouch,longStroke=test.length>0;
    if(w<128||h<128||w>8192||h>8192||test.brush<1||test.brush>512||test.repeat<1||test.repeat>16)return 2;
    const Extent2u extent{std::uint32_t(w),std::uint32_t(h)};Document document({extent});
    const double sx=test.x>=0?test.x:w*.37,sy=test.y>=0?test.y:h*.43,length=test.length;
    const auto curve=[&](double x){return sy+(longStroke?std::min(30.,length*.15)*std::sin((x-sx)/length*3.141592653589793):0.);};
    std::vector<std::byte> storage(std::size_t(w)*std::size_t(h)*4);
    for(int y=0;y<h;++y)for(int x=0;x<w;++x){
        const double grain=4*noise(x,y,7723)+7*std::sin(x*.23+std::sin(y*.06));
        auto red=std::uint8_t(std::clamp(136.+grain,0.,255.));
        auto green=std::uint8_t(std::clamp(111.+grain*.7,0.,255.));
        auto blue=std::uint8_t(std::clamp(89.+grain*.4,0.,255.));
        std::uint8_t alpha=255;
        if(!photograph.isNull()){
            const auto* original=photograph.constScanLine(y)+x*4;
            red=original[0];green=original[1];blue=original[2];
            if(test.originalPhoto)alpha=original[3];
        }
        const bool damage=longStroke?(x>=sx&&x<=sx+length&&std::abs(y-curve(x))<2.):std::hypot(x-sx,y-sy)<3.;
        if(damage&&!test.originalPhoto){red=244;green=22;blue=98;}
        const auto i=(std::size_t(y)*std::size_t(w)+std::size_t(x))*4;
        storage[i]=std::byte(red);storage[i+1]=std::byte(green);storage[i+2]=std::byte(blue);storage[i+3]=std::byte{alpha};
    }
    auto surface=std::make_shared<ContiguousRasterSurface>(extent,std::move(storage));
    auto layer=Layer::raster("Spot Heal performance",surface);auto id=layer.id;
    if(!document.insertLayer(0,std::move(layer)))return 2;
    const auto source=surface;const auto sourceRevision=source->revision();
    if(retouch){
        surface=std::make_shared<ContiguousRasterSurface>(extent,Rgba8{});
        auto empty=Layer::raster("Empty Normal retouch",surface);id=empty.id;
        if(!document.insertLayer(1,std::move(empty)))return 2;
    }
    document.markSaved();
    auto brush=proceduralBrushPreset(ProceduralBrushPreset::HardRound);brush.sizePixels=test.brush;
    brush.hardness=.85;brush.opacity=1;brush.flow=1;brush.pressureToFlow=false;brush.pressureToSize=false;brush.spacingPercent=15;
    CloneSettings settings;settings.mode=CloneMode::SpotHeal;
    settings.source=retouch?CloneSampleSource::CurrentAndBelow:CloneSampleSource::SourceLayer;
    const auto sample=[](double x,double y,std::uint64_t time){return NormalizedPointerSample{.documentPosition={x,y},
        .timestampMicroseconds=time,.pressure=1,.pointerType=PointerType::Mouse,.buttons=PointerButtonPrimary};};
    const auto start=std::chrono::steady_clock::now();std::string diagnostic;
    auto reference=CloneReference::capture(document,id,id,settings.source,diagnostic,
        CloneReference::defaultSnapshotLimit,false,{}, {},true);
    if(!reference){std::cerr<<diagnostic<<'\n';return 1;}
    const auto frozen=std::chrono::steady_clock::now();
    SpotHealStroke stroke(document,id,brush,settings,std::move(*reference));
    if(!stroke.begin(sample(sx,sy,0))){std::cerr<<stroke.diagnostic()<<'\n';return 1;}
    if(longStroke)for(int i=1;i<40;++i){const double x=sx+length*i/40.;stroke.append(sample(x,curve(x),std::uint64_t(i)*10000));}
    const auto work=stroke.finishInput(sample(sx+length,curve(sx+length),400000));
    if(!work){std::cerr<<stroke.diagnostic()<<'\n';return 1;}
    const auto marked=std::chrono::steady_clock::now();
    SpotHealOptions options;
#ifndef SPOT_HEAL_FROZEN_BASELINE
    options.captureProfile=test.profile;options.workerCount=test.workers;
#endif
    const auto cpuStart=cpuMilliseconds();
#ifdef SPOT_HEAL_COUNT_ALLOCATIONS
    allocationProfile::enabled.store(true,std::memory_order_relaxed);
#endif
    const auto solved=SpotHealStroke::solve(work,options);
#ifdef SPOT_HEAL_COUNT_ALLOCATIONS
    allocationProfile::enabled.store(false,std::memory_order_relaxed);
    const auto allocationCalls=allocationProfile::calls.load(),allocationBytes=allocationProfile::bytes.load();
#endif
    const auto cpuEnd=cpuMilliseconds();
    const auto finished=std::chrono::steady_clock::now();History history;
    if(!solved.repair){std::cerr<<"Performance solve: "<<statusName(solved.repair.status)<<" "<<solved.repair.diagnostics.message<<'\n';stroke.cancel();return 1;}
    const auto commit=stroke.publish(solved,history);
    const auto published=std::chrono::steady_clock::now();
    const auto ms=[](auto a,auto b){return std::chrono::duration<double,std::milli>(b-a).count();};
    std::cout<<std::fixed<<std::setprecision(3)<<w<<'x'<<h<<','<<(longStroke?"curved-stroke":"small-spot")<<','<<(retouch?"retouch":"raw")
        <<",brush_px="<<test.brush<<",length_px="<<length<<",fixture="<<(photograph.isNull()?"synthetic-texture":QFileInfo(test.photo).fileName().toStdString())
        <<",original_photo="<<test.originalPhoto
        <<",capture_ms="<<ms(start,frozen)<<",mark_ms="<<ms(frozen,marked)<<",solve_ms="<<ms(marked,finished)
        <<",solve_cpu_ms="<<cpuEnd-cpuStart<<",solve_cpu_cores="<<(cpuEnd-cpuStart)/std::max(.001,ms(marked,finished))
        <<",publish_ms="<<ms(finished,published)<<",total_ms="<<ms(start,published)
        <<",rss_peak_mib="<<peakResidentMiB()<<",snapshot_bytes="<<stroke.snapshotBytes()
        <<",prepared_bytes="<<solved.preparedBytes<<",solver_estimate_bytes="<<solved.repair.diagnostics.estimatedPeakWorkingBytes
        <<",roi="<<solved.gridBounds.width<<'x'<<solved.gridBounds.height<<",regional_write_bytes="<<stroke.stats().uploadedRegionBytes
        <<",unknown_pixels="<<solved.repair.diagnostics.unknownPixels<<",patch_radius="<<solved.repair.diagnostics.patchRadius
        <<",pyramid_levels="<<solved.repair.diagnostics.pyramidLevels<<",comparisons="<<solved.repair.diagnostics.comparisons
        <<",smooth_model_pixels="<<solved.repair.diagnostics.smoothModelPixels<<",history_entries="<<history.undoDepth()<<'\n';
#ifndef SPOT_HEAL_FROZEN_BASELINE
    if(test.profile)printProfile(solved);
#endif
#ifdef SPOT_HEAL_COUNT_ALLOCATIONS
    std::cout<<"allocation_profile,cpp_new_calls="<<allocationCalls<<",cpp_requested_bytes="<<allocationBytes<<'\n';
#endif
    const auto candidateHash=fingerprint(solved.repair.pixels.data(),solved.repair.pixels.size()*sizeof(PremultipliedColor));
    const auto preview=stroke.previewMask();const auto region=preview->bounds();
    std::vector<std::byte> output(std::size_t(region.width)*std::size_t(region.height)*4);
    surface->copyRgba8(region,output,std::size_t(region.width)*4);
    std::vector<std::uint8_t> mask(std::size_t(region.width)*std::size_t(region.height));
    for(int y=0;y<region.height;++y)for(int x=0;x<region.width;++x)
        mask[std::size_t(y*region.width+x)]=preview->coverageAtDocumentPixel(x+region.x,y+region.y);
    std::cout<<"candidate_float_sha256="<<candidateHash<<",stored_region_sha256="<<fingerprint(output.data(),output.size())
        <<",mark_sha256="<<fingerprint(mask.data(),mask.size())<<",mark_bounds="<<region.x<<':'<<region.y<<':'<<region.width<<':'<<region.height<<'\n';
    if(!test.dump.isEmpty()){
        check(QDir().mkpath(test.dump),"create performance dump directory");
        maskImage(mask,region.width,region.height).save(test.dump+"/mark.png");
        image(solved.repair.pixels,solved.gridBounds.width,solved.gridBounds.height).save(test.dump+"/candidate.png");
        std::ofstream binary((test.dump+"/candidate-linear-rgba-f32.bin").toStdString(),std::ios::binary);
        binary.write(reinterpret_cast<const char*>(solved.repair.pixels.data()),std::streamsize(solved.repair.pixels.size()*sizeof(PremultipliedColor)));
        QImage(reinterpret_cast<const uchar*>(output.data()),region.width,region.height,region.width*4,QImage::Format_RGBA8888).save(test.dump+"/stored-region.png");
        if(!photograph.isNull()){
            photograph.copy(region.x,region.y,region.width,region.height).save(test.dump+"/clean-region.png");
            double error=0;std::size_t count=0;
            for(int y=0;y<region.height;++y)for(int x=0;x<region.width;++x){
                const auto i=std::size_t(y*region.width+x);if(!mask[i])continue;
                const auto gx=region.x+x-solved.gridBounds.x,gy=region.y+y-solved.gridBounds.y;
                const auto& candidate=solved.repair.pixels[std::size_t(gy*solved.gridBounds.width+gx)];
                const auto* pixel=photograph.constScanLine(region.y+y)+(region.x+x)*4;
                const auto truth=decodeColor({pixel[0],pixel[1],pixel[2],pixel[3]});
                for(std::size_t c=0;c<3;++c){error+=std::abs(candidate[c]/std::max(candidate[3],1e-20F)-truth[c]/std::max(truth[3],1e-20F));++count;}
            }
            std::cout<<(test.originalPhoto?"masked_source_change_linear_mae=":"photographic_unknown_linear_mae=")
                <<error/double(std::max(std::size_t(1),count))<<'\n';
        }
    }
    for(int repeat=1;repeat<test.repeat;++repeat){
        const auto repeatedStart=std::chrono::steady_clock::now();const auto repeatedCpu=cpuMilliseconds();
        const auto repeated=SpotHealStroke::solve(work,options);const auto repeatedEnd=std::chrono::steady_clock::now();
        check(repeated.repair.pixels==solved.repair.pixels,"warm repair exactly reproduces cold candidate");
        std::cout<<"warm_repeat="<<repeat<<",solve_ms="<<ms(repeatedStart,repeatedEnd)<<",solve_cpu_ms="<<cpuMilliseconds()-repeatedCpu
            <<",rss_peak_mib="<<peakResidentMiB()<<'\n';
    }
    check(commit==RasterEditCommitResult::Committed&&history.undoDepth()==1,"performance stroke commits exactly once");
    if(retouch)check(source->revision()==sourceRevision,"retouch performance leaves the underlying source unchanged");
    if(!test.cancelCheck)return failures?1:0;
    const auto revision=surface->revision();const auto cancelStart=std::chrono::steady_clock::now();SpotHealOptions cancel;
    cancel.cancelled=[&]{return ms(cancelStart,std::chrono::steady_clock::now())>=25.;};
    const auto stopped=SpotHealStroke::solve(work,cancel);const auto stoppedAt=std::chrono::steady_clock::now();
    std::cout<<"cancel_deadline_ms=25,cancel_total_ms="<<ms(cancelStart,stoppedAt)
        <<",overshoot_ms="<<std::max(0.,ms(cancelStart,stoppedAt)-25.)<<",status="<<statusName(stopped.repair.status)<<'\n';
    check(stopped.repair.status==SpotHealStatus::Cancelled&&surface->revision()==revision&&history.undoDepth()==1,"cancelled independent solve never publishes");
    return failures?1:0;
}
