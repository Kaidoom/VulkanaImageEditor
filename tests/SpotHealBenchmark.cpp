Fixture makeFixture(int material,int damage,unsigned seed,bool heldout)
{
    const std::array names{"gradient","skin","fabric","wood","stone","grass","grain","grid","edge","lineart","alpha","insufficient","alpha-edge","image-edge"};
    Fixture f;f.name=(heldout?"heldout-":"dev-")+std::string(names[std::size_t(material)]);
    f.input.w=width;f.input.h=height;const auto count=std::size_t(width*height);
    f.clean.resize(count);f.input.unknown.resize(count);f.input.valid.assign(count,255);f.write.resize(count);
    f.alpha=material==10||material==12;f.insufficient=material==11;
    const int kind=material==12?10:(material==13?3:material);
    for(int y=0;y<height;++y)for(int x=0;x<width;++x){
        const double u=double(x)/width,v=double(y)/height,n=noise(x,y,seed),
            low=smoothNoise(x/14.,y/14.,seed),fine=smoothNoise(x/2.1,y/2.1,seed+1);
        PremultipliedColor pixel;
        switch(kind){
        case 0:pixel=color(.18+.32*u+.06*v,.24+.18*u+.10*v,.3+.06*u-.08*v);break;
        case 1:{const double pores=.012*fine+.007*n+.025*low;
            pixel=color(.45+.13*u+pores,.23+.09*u+pores*.7,.17+.06*u+pores*.55);break;}
        case 2:{const double weave=.05*std::sin(x*1.57)+.04*std::cos(y*1.57)+.02*std::sin((x+y)*.785);
            pixel=color(.28+weave+.03*u,.36+weave,.42+weave+.01*n);break;}
        case 3:{const double rings=.08*std::sin(x*.24+std::sin(y*.06)*1.4+low*.6)+.035*std::sin(x*.79+low);
            pixel=color(.34+rings+.012*n,.18+rings*.65,.075+rings*.3);break;}
        case 4:{const double rock=.09*low+.07*fine+.035*n;
            pixel=color(.37+rock,.39+rock*.95,.35+rock*.9);break;}
        case 5:{const double blades=.07*std::sin(x*.95+y*.35+low)+.055*fine+.022*n;
            pixel=color(.11+blades*.55,.27+blades,.065+blades*.4);break;}
        case 6:pixel=color(.27+.10*u+.025*n,.34+.07*v+.023*n,.42+.018*n);break;
        case 7:{const int bx=(x+(y/22%2)*12)%24,by=y%22;const bool mortar=bx<2||by<2;
            pixel=mortar?color(.12,.14,.15):color(.5+.018*fine,.24+.012*fine,.13+.012*fine);break;}
        case 8:{const double edge=std::clamp((x-96.+.13*(y-72.))/1.2+.5,0.,1.);
            pixel=color(std::lerp(.08,.72,edge)+.005*n,std::lerp(.11,.54,edge),std::lerp(.16,.34,edge));break;}
        case 9:{const double line=std::min(std::abs(y-70.-.2*(x-96.)),std::abs(y-42.+.12*(x-96.)));
            const double ink=std::clamp((line-.7)/1.1,0.,1.);pixel=color(.035+.73*ink,.025+.69*ink,.04+.62*ink);break;}
        case 10:{const double a=material==12?std::clamp((x-75.)/35.,0.,1.):.15+.65*u;pixel=color(.24+.14*u+.02*n,.37+.02*n,.51+.02*n,a);break;}
        default:pixel=color(.35+.01*n,.4,.45);break;
        }
        // Match the authoritative RGBA8 input boundary for every comparator,
        // including the independently launched PNG reference.
        const auto i=f.input.at(x,y);f.clean[i]=decodeColor(encodeColor(pixel));
        double distance=1000;
        if(damage==0)distance=std::hypot(x-(material==12?79.:96.),y-72.)-8;
        if(damage==1)distance=std::min({std::hypot(x-81.,y-65.)-6,std::hypot(x-106.,y-81.)-8,std::hypot(x-119.,y-59.)-4});
        if(damage==2&&x>=39&&x<=153)distance=std::abs(y-(72.+18*std::sin((x-40.)*.034)))-3.2;
        if(damage==3&&y>=25&&y<=117)distance=std::abs(x-(96.+8*std::sin(y*.07)))-3.6;
        if(damage==4)distance=std::hypot(x-1.,y-71.)-10;
        if(material==11)distance=-10;
        if(distance<1){f.input.unknown[i]=255;f.write[i]=float(std::clamp(1-distance,0.,1.));}
    }
    f.input.pixels=f.clean;
    // Feather support is conservatively unknown too, but damage lies fully
    // under opaque write coverage. This avoids intentionally leaving blemish
    // residue in the comparison finals simply because of partial opacity.
    for(std::size_t i=0;i<count;++i)if(f.write[i]>=1)
        f.input.pixels[i]=decodeColor(encodeColor(color(.9,.025,.19,f.clean[i][3])));
    return f;
}
Pixels finalize(const Input& input,const Pixels& candidate,const std::vector<float>& write)
{
    Pixels result=input.pixels;if(candidate.size()!=result.size())return result;
    for(std::size_t i=0;i<result.size();++i)if(write[i]>0){
        // Direct-repair policy: destination alpha retained; final coverage once.
        for(std::size_t channel=0;channel<3;++channel){
            const float replacement=candidate[i][3]>0?candidate[i][channel]/candidate[i][3]*result[i][3]:result[i][channel];
            result[i][channel]=std::lerp(result[i][channel],replacement,write[i]);
        }
    }
    return result;
}
Answer diffuse(const Input& input)
{
    const auto start=std::chrono::steady_clock::now();Answer result;result.status="complete";result.pixels=input.pixels;
    PremultipliedColor mean{};double weight=0;
    for(std::size_t i=0;i<input.pixels.size();++i)if(!input.unknown[i]&&input.valid[i]&&input.pixels[i][3]>0){
        for(std::size_t c=0;c<3;++c)mean[c]+=input.pixels[i][c];
        weight+=input.pixels[i][3];
    }
    if(weight==0){result.status="insufficient-context";result.pixels.clear();return result;}
    for(auto& channel:mean)channel=float(channel/weight);
    for(std::size_t i=0;i<result.pixels.size();++i)if(input.unknown[i]){
        for(std::size_t c=0;c<3;++c)result.pixels[i][c]=mean[c]*input.pixels[i][3];
    }
    for(int iteration=0;iteration<1200;++iteration){double change=0;
        for(int parity=0;parity<2;++parity)for(int y=0;y<input.h;++y)for(int x=(y+parity)%2;x<input.w;x+=2){
            const auto i=input.at(x,y);if(!input.unknown[i])continue;
            std::array<double,3> sum{};double alpha=0;
            for(auto [dx,dy]:std::array<std::pair<int,int>,4>{{{-1,0},{1,0},{0,-1},{0,1}}}){
                if(x+dx<0||y+dy<0||x+dx>=input.w||y+dy>=input.h)continue;
                const auto j=input.at(x+dx,y+dy);if(!input.valid[j])continue;
                alpha+=result.pixels[j][3];for(std::size_t c=0;c<3;++c)sum[c]+=result.pixels[j][c];
            }
            if(alpha>0)for(std::size_t c=0;c<3;++c){const float value=float(sum[c]/alpha*input.pixels[i][3]);change=std::max(change,double(std::abs(value-result.pixels[i][c])));result.pixels[i][c]=value;}
        }
        if(change<1e-6)break;
    }
    result.ms=std::chrono::duration<double,std::milli>(std::chrono::steady_clock::now()-start).count();return result;
}
Answer singlePatch(const Input& input)
{
    const auto start=std::chrono::steady_clock::now();Answer result;result.status="insufficient-context";
    int left=input.w,top=input.h,right=-1,bottom=-1;
    for(int y=0;y<input.h;++y)for(int x=0;x<input.w;++x)if(input.unknown[input.at(x,y)]){left=std::min(left,x);right=std::max(right,x);top=std::min(top,y);bottom=std::max(bottom,y);}
    if(right<left)return result;
    left=std::max(0,left-6);top=std::max(0,top-6);right=std::min(input.w-1,right+6);bottom=std::min(input.h-1,bottom+6);
    std::vector<std::pair<int,int>> context;
    for(int y=top;y<=bottom;++y)for(int x=left;x<=right;++x)if(!input.unknown[input.at(x,y)]&&input.valid[input.at(x,y)]&&input.pixels[input.at(x,y)][3]>0)context.emplace_back(x,y);
    if(context.size()<8)return result;
    // Whole translated source rectangle is valid, not merely its center.
    std::vector<int> invalid(std::size_t((input.w+1)*(input.h+1)));
    for(int y=0;y<input.h;++y)for(int x=0;x<input.w;++x){const auto p=input.at(x,y);const auto at=std::size_t((y+1)*(input.w+1)+x+1);
        invalid[at]=int(input.unknown[p]||!input.valid[p]||input.pixels[p][3]<=0)+invalid[at-1]+invalid[at-std::size_t(input.w+1)]-invalid[at-std::size_t(input.w+2)];}
    double best=std::numeric_limits<double>::infinity();int bestX=0,bestY=0;
    for(int dy=-top;dy<input.h-bottom;++dy)for(int dx=-left;dx<input.w-right;++dx){
        const int x0=left+dx,y0=top+dy,x1=right+dx+1,y1=bottom+dy+1,stride=input.w+1;
        if(invalid[std::size_t(y1*stride+x1)]-invalid[std::size_t(y0*stride+x1)]-invalid[std::size_t(y1*stride+x0)]+invalid[std::size_t(y0*stride+x0)])continue;
        double score=0;for(auto [x,y]:context){const auto& a=input.pixels[input.at(x,y)];const auto& b=input.pixels[input.at(x+dx,y+dy)];
            for(std::size_t c=0;c<3;++c){const double d=a[c]/a[3]-b[c]/b[3];score+=d*d;}if(score>best)break;}
        score+=double(dx*dx+dy*dy)*1e-10;if(score<best){best=score;bestX=dx;bestY=dy;}
    }
    if(!std::isfinite(best))return result;
    Pixels source=input.pixels;std::vector<float> coverage(input.pixels.size());
    for(int y=top;y<=bottom;++y)for(int x=left;x<=right;++x){const auto i=input.at(x,y);source[i]=input.pixels[input.at(x+bestX,y+bestY)];coverage[i]=input.unknown[i]?1:0;}
    const auto healed=healPatch({input.w,input.h,source,input.pixels,coverage});
    if(!healed.pixels.empty()){
        result.pixels=healed.pixels;
        for(std::size_t i=0;i<result.pixels.size();++i)if(!input.unknown[i])result.pixels[i]=input.pixels[i];
        result.status=healed.status==HealingStatus::Converged?"complete":"reported-heal-fallback";
    }
    result.donorX=bestX;result.donorY=bestY;
    result.ms=std::chrono::duration<double,std::milli>(std::chrono::steady_clock::now()-start).count();return result;
}
QImage image(const Pixels& pixels,int w,int h)
{
    QImage result(w,h,QImage::Format_RGBA8888);result.fill(Qt::transparent);
    if(pixels.size()!=std::size_t(w*h))return result;
    for(int y=0;y<h;++y)for(int x=0;x<w;++x){const auto c=encodeColor(pixels[std::size_t(y*w+x)]);result.setPixelColor(x,y,QColor(c.red,c.green,c.blue,c.alpha));}
    return result;
}
QImage maskImage(const std::vector<std::uint8_t>& mask,int w,int h)
{
    QImage result(w,h,QImage::Format_RGB888);for(int y=0;y<h;++y)for(int x=0;x<w;++x){const auto v=mask[std::size_t(y*w+x)];result.setPixelColor(x,y,QColor(v,v,v));}return result;
}
Pixels decode(const QImage& original)
{
    const auto input=original.convertToFormat(QImage::Format_RGBA8888);Pixels result(std::size_t(input.width()*input.height()));
    for(int y=0;y<input.height();++y)for(int x=0;x<input.width();++x){const auto* p=input.constScanLine(y)+x*4;result[std::size_t(y*input.width()+x)]=decodeColor({p[0],p[1],p[2],p[3]});}
    return result;
}
Answer independent(const Input& input,const QString& executable,const QString& directory,bool alpha)
{
    Answer answer;answer.status=alpha?"unsupported-alpha":"not-run";
    if(executable.isEmpty()||alpha)return answer;
    const auto start=std::chrono::steady_clock::now();QProcess process;process.setWorkingDirectory(directory);
    const auto output=directory+"/ipol.png";
    // Explicitly feed three-channel RGB. QImage's normal RGBA8888 writer would
    // otherwise add an opaque fourth channel to the independent cost function.
    const auto rgb=directory+"/reference-rgb.png";
    if(!image(input.pixels,input.w,input.h).convertToFormat(QImage::Format_RGB888).save(rgb)){
        answer.status="input-write-failed";return answer;
    }
    process.start(executable,{rgb,directory+"/unknown.png",output});
    if(!process.waitForStarted(3000)){answer.status="launch-failed";return answer;}
    if(!process.waitForFinished(120000)){process.kill();process.waitForFinished(3000);answer.status="timeout";}
    else if(process.exitStatus()!=QProcess::NormalExit||process.exitCode()!=0)answer.status="process-failed";
    else {const QImage result(output);if(result.size()==QSize(input.w,input.h)){answer.status="complete";answer.pixels=decode(result);}else answer.status="invalid-output";}
    std::ofstream log((directory+"/ipol.log").toStdString());log<<process.readAllStandardOutput().toStdString()<<process.readAllStandardError().toStdString();
    answer.ms=std::chrono::duration<double,std::milli>(std::chrono::steady_clock::now()-start).count();return answer;
}
struct Metrics {double mae{},boundary{},detail{};};
Metrics metrics(const Fixture& f,const Pixels& output)
{
    Metrics m;double n=0,bn=0,truthEnergy=0,outEnergy=0;
    for(int y=0;y<f.input.h;++y)for(int x=0;x<f.input.w;++x){const auto i=f.input.at(x,y);if(!f.input.unknown[i]||f.clean[i][3]<=0)continue;
        for(std::size_t c=0;c<3;++c){m.mae+=std::abs(output[i][c]/std::max(output[i][3],1e-20F)-f.clean[i][c]/f.clean[i][3]);++n;}
        for(auto [dx,dy]:std::array<std::pair<int,int>,4>{{{1,0},{0,1},{-1,0},{0,-1}}}){
            if(x+dx<0||y+dy<0||x+dx>=f.input.w||y+dy>=f.input.h)continue;
            const auto j=f.input.at(x+dx,y+dy);
            if(f.clean[j][3]<=0)continue;
            for(std::size_t c=0;c<3;++c){
                const double truth=f.clean[i][c]/f.clean[i][3]-f.clean[j][c]/f.clean[j][3];
                const double estimated=output[i][c]/std::max(output[i][3],1e-20F)-output[j][c]/std::max(output[j][3],1e-20F);
                if(!f.input.unknown[j]){m.boundary+=std::abs(truth-estimated);++bn;}
                else if(dx>0||dy>0){truthEnergy+=truth*truth;outEnergy+=estimated*estimated;}
            }
        }
    }
    m.mae/=std::max(1.,n);m.boundary/=std::max(1.,bn);m.detail=truthEnergy>1e-20?std::sqrt(outEnergy/truthEnergy):0;return m;
}
void saveDiagnostic(const Fixture& f,const SpotHealResult& result,const QString& directory)
{
    std::ofstream information((directory+"/diagnostics.txt").toStdString());
    information<<"Unknown: "<<result.diagnostics.unknownPixels<<"\nValid donor centers: "<<result.diagnostics.validDonorCenters
        <<"\nPatch radius: "<<result.diagnostics.patchRadius<<"\nPyramid levels: "<<result.diagnostics.pyramidLevels
        <<"\nComparisons: "<<result.diagnostics.comparisons<<"\nEstimated peak bytes: "<<result.diagnostics.estimatedPeakWorkingBytes
        <<"\nValidated smooth-model pixels: "<<result.diagnostics.smoothModelPixels
        <<"\nAdaptation applied: "<<result.diagnostics.adaptationApplied<<"\n"<<result.diagnostics.message<<'\n';
    if(result.diagnostics.invalidDonors.size()==f.input.pixels.size())maskImage(result.diagnostics.invalidDonors,width,height).save(directory+"/invalid-donor-centers.png");
    if(!result.diagnostics.beforeAdaptation.empty())image(result.diagnostics.beforeAdaptation,width,height).save(directory+"/before-adaptation.png");
    if(result.diagnostics.donors.size()!=f.input.pixels.size())return;
    QImage donors(width,height,QImage::Format_RGB888);donors.fill(Qt::black);
    for(std::size_t i=0;i<result.diagnostics.donors.size();++i){const auto d=result.diagnostics.donors[i];if(d.x<0||d.y<0)continue;
        check(d.x<width&&d.y<height,"donor assignment remains in input");if(d.x>=width||d.y>=height)continue;
        check(!f.input.unknown[f.input.at(d.x,d.y)]&&f.input.valid[f.input.at(d.x,d.y)],"donor center never comes from unknown or invalid data");
        if(!result.diagnostics.invalidDonors.empty())check(result.diagnostics.invalidDonors[f.input.at(d.x,d.y)]==0,"diagnostic donor respects complete-patch invalidity map");
        donors.setPixelColor(int(i%width),int(i/width),QColor(d.x*255/width,d.y*255/height,150));
    }
    donors.save(directory+"/donor-assignments.png");
}
